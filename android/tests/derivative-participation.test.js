const assert=require('node:assert/strict');
const P=require('../app/src/main/assets/derivative-participation.js');
const now=Date.parse('2026-10-27T05:00:00Z');
const make=(q)=>({data:{futures:[{expiry:'2026-12-29',lot_size:100,quote:q}]},fetched_at_iso:new Date(now).toISOString()});
const fresh={last_price:5100,prev_close:5000,open_interest:12000,previous_oi:10000,volume:15400,bid:5099,ask:5101,quote_as_of:new Date(now-15000).toISOString(),last_trade_at:new Date(now-30000).toISOString()};
let row=P.inspect(make(fresh),now).rows[0];
assert.equal(row.state,'recent');
assert.equal(row.pattern,'Rising price + rising OI');
assert.equal(Math.round(row.oiPct),20);
assert.ok(row.spread>0);
assert.equal(P.inspect(make({...fresh,last_price:4900}),now).rows[0].pattern,'Falling price + rising OI');
assert.equal(P.inspect(make({...fresh,open_interest:9000}),now).rows[0].pattern,'Rising price + falling OI');
assert.equal(P.inspect(make({...fresh,open_interest:9000,last_price:4900}),now).rows[0].pattern,'Falling price + falling OI');
assert.equal(P.inspect(make({...fresh,previous_oi:null}),now).rows[0].oiPct,null);
assert.equal(P.inspect(make({...fresh,quote_as_of:null}),now).rows[0].state,'clock-incomplete');
assert.equal(P.inspect(make({...fresh,last_trade_at:new Date(now-180000).toISOString()}),now).rows[0].state,'older');
assert.equal(P.inspect(make({...fresh,bid:5102,ask:5101}),now).rows[0].spread,null);
assert.ok(P.markup(make(fresh),[{type:'FUT',expiry:'2026-12-29'}],now).includes('YOUR FUTURES'));
assert.ok(!P.markup(make({...fresh,expiry:'<bad>'}),[],now).includes('<bad>'));
assert.ok(P.markup(null,[],now).includes('No HAL futures'));
console.log('HAL futures participation V3 tests passed');
